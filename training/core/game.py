from typing import Protocol

class Game(Protocol):
    ACTION_SIZE: int
    def initialState(self) -> dict: ...
    def legalMoves(self, state: dict) -> list[bool]: ...
    def applyMove(self, state: dict, action: int) -> dict: ...
    def isTerminal(self, state: dict) -> dict: ...
    def encode(self, state: dict) -> list[list[list[float]]]: ...
    def symmetries(self, state: dict, policy: list[float]) -> list[tuple[dict, list[float]]]: ...
